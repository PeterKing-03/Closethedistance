  const UNITS = UNIT_GROUPS.flatMap(([, list]) => list);

  function unit(key, amount) {
    if (en() && amount != null && amount !== 1 && STR.en['unit.' + key + '.pl']) return STR.en['unit.' + key + '.pl'];
    return t('unit.' + key);
  }

